/** Which sides of which levels are taken by a named room. */
export const SPECIAL_SIDES = (() => {
  const m = new Map();
  for (const p of PLACES) {
    if (p.kind !== 'room' || !p.side || p.level > 144) continue;
    const e = m.get(p.level) || {};
    e[p.side] = p.id;
    m.set(p.level, e);
  }
  return m;
})();

